"""Latency benchmark for the serving path, hedging off vs on. Writes eval/latency.md.

    uv run --env-file .env python -m eval.latency_bench --n 40

Runs pata.service.triage (the gateway's code path, minus HTTP) one request at a time, the way
a dispatcher pastes addresses. Each request is a Sentry transaction tagged with hedge_ms when
SENTRY_DSN is set (environment "bench"), so the screenshots and this table come from one run.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import statistics
from datetime import UTC, datetime
from pathlib import Path

import sentry_sdk

from pata.client import TINKER_OAI_URL, ModelClient, default_api_key
from pata.schema import TriageInput
from pata.service import triage

TEST = Path("data/splits/test.jsonl")
OUT = Path("eval/latency.md")
CHECKPOINT = "tinker://66ebff6a-2896-584d-9189-64032bad9b83:train:0/sampler_weights/final"
# Tinker sampling rates for Qwen3.5-4B, USD per million tokens (train/RUNS.md, billing usage)
PREFILL_PER_M, SAMPLE_PER_M = 0.33, 1.005


def pct(xs: list[float], p: float) -> float:
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(p * len(xs)))]


async def run_mode(inputs: list[TriageInput], url: str, model: str, hedge_ms: int) -> dict:
    client = ModelClient(url, default_api_key(url), model, hedge_ms=hedge_ms)
    lat, tin, tout, hedged, model_answers = [], [], [], 0, 0
    try:
        for inp in inputs:
            with sentry_sdk.start_transaction(op="bench", name="triage") as tx:
                tx.set_tag("hedge_ms", hedge_ms)
                res = await triage(inp, client)
            lat.append(res.latency_ms / 1000)
            tin.append(res.input_tokens)
            tout.append(res.output_tokens)
            hedged += bool(res.hedged)
            model_answers += res.source == "model"
    finally:
        await client.aclose()
    return {
        "hedge_ms": hedge_ms, "n": len(lat), "p50": pct(lat, 0.5), "p90": pct(lat, 0.9),
        "mean": statistics.mean(lat), "max": max(lat), "over5": sum(x > 5 for x in lat),
        "hedged": hedged, "model": model_answers,
        "in_tokens": statistics.mean(tin), "out_tokens": statistics.mean(tout),
    }


def write(results: list[dict], model: str, n: int) -> None:
    off, on = results
    per_call = (on["in_tokens"] * PREFILL_PER_M + on["out_tokens"] * SAMPLE_PER_M) / 1e6
    hedge_share = on["hedged"] / on["n"]
    lines = [
        "# Serving latency", "",
        "Generated by `eval/latency_bench.py`. Do not edit by hand.", "",
        f"* {datetime.now(UTC).strftime('%Y-%m-%d %H:%M UTC')}, model `{model}` on Tinker's "
        f"OpenAI-compatible endpoint, {n} sequential requests per mode from the test split, "
        "through `pata.service.triage`.", "",
        "| | Hedging off | Hedging on (1.5 s) |",
        "|---|---|---|",
    ]
    for key, name, fmt in [
        ("p50", "p50", "{:.2f} s"), ("p90", "p90", "{:.2f} s"), ("mean", "Mean", "{:.2f} s"),
        ("max", "Max", "{:.2f} s"), ("over5", "Requests over 5 s", "{} of " + str(n)),
        ("hedged", "Requests hedged", "{} of " + str(n)),
        ("model", "Answered by the model", "{} of " + str(n)),
        ("in_tokens", "Mean input tokens", "{:.0f}"),
        ("out_tokens", "Mean output tokens", "{:.0f}"),
    ]:
        lines.append(f"| {name} | {fmt.format(off[key])} | {fmt.format(on[key])} |")
    lines += [
        "",
        f"Cost per call at ${PREFILL_PER_M} per million prefill and ${SAMPLE_PER_M} per million "
        f"sampled tokens: ${per_call:.6f}, or ${per_call * 10_000:.2f} per 10,000 parcels. "
        f"Hedging sent a second call on {hedge_share:.0%} of requests; counting each as a full "
        f"extra call, the upper bound is ${per_call * (1 + hedge_share) * 10_000:.2f} "
        "per 10,000 parcels.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    (OUT.with_suffix(".json")).write_text(json.dumps(results, indent=1), encoding="utf-8")


async def amain(args: argparse.Namespace) -> None:
    rows = [json.loads(x) for x in TEST.read_text("utf-8").splitlines()]
    inputs = [TriageInput.model_validate(r["input"]) for r in rows][args.offset:][: args.n]
    results = [await run_mode(inputs, args.url, args.model, h) for h in (0, args.hedge_ms)]
    for r in results:
        print(r)
    write(results, args.model, len(inputs))
    print(f"wrote {OUT}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=40)
    ap.add_argument("--offset", type=int, default=100)
    ap.add_argument("--hedge-ms", type=int, default=1500)
    ap.add_argument("--url", default=TINKER_OAI_URL)
    ap.add_argument("--model", default=CHECKPOINT)
    args = ap.parse_args()
    if dsn := os.environ.get("SENTRY_DSN"):
        sentry_sdk.init(dsn=dsn, traces_sample_rate=1.0, send_default_pii=False,
                        environment="bench")
    asyncio.run(amain(args))
    sentry_sdk.flush()


if __name__ == "__main__":
    main()
